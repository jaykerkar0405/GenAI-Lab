# %% [markdown]
# # Experiment 7: Text Generation using Recurrent Neural Networks (RNNs) and LSTMs
#
# **Aim:** Build character-level language models with a simple RNN and an LSTM on Shakespeare's text, train them with
# next-character prediction, and generate new text with different sampling temperatures.

# %% title: Imports and data
import os, time
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
import numpy as np, matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
keras.utils.set_random_seed(11)
path = keras.utils.get_file("shakespeare.txt", "https://storage.googleapis.com/download.tensorflow.org/data/shakespeare.txt")
text = open(path, encoding="utf-8").read()
chars = sorted(set(text)); V = len(chars)
c2i = {c: i for i, c in enumerate(chars)}; i2c = np.array(chars)
data = np.array([c2i[c] for c in text], dtype=np.int32)
print("characters used:", len(text), "| vocabulary size:", V)
print(text[:200])

# %% [markdown]
# ## 1. Training sequences
# Every training example is a window of 100 characters; the target is the same window shifted one character to the right,
# so the model predicts the next character at every position.

# %% title: Building the tf.data pipeline of (input, target) windows
SEQ, BATCH, STRIDE = 100, 128, 50
starts = np.arange(0, len(data) - SEQ - 1, STRIDE)                 # overlapping windows
X = np.stack([data[i:i + SEQ] for i in starts]); Y = np.stack([data[i + 1:i + SEQ + 1] for i in starts])
perm = np.random.RandomState(0).permutation(len(X)); n_val = len(X) // 20
val_ds = tf.data.Dataset.from_tensor_slices((X[perm[:n_val]], Y[perm[:n_val]])).batch(BATCH)
train_ds = (tf.data.Dataset.from_tensor_slices((X[perm[n_val:]], Y[perm[n_val:]])).shuffle(5000, seed=0)
            .batch(BATCH, drop_remainder=True).prefetch(2))
print("windows:", len(X), "| train batches:", len(train_ds), "| val windows:", n_val)
print("input :", repr("".join(i2c[X[0][:50]])))
print("target:", repr("".join(i2c[Y[0][:50]])))

# %% [markdown]
# ## 2. Models: SimpleRNN vs LSTM
# An LSTM cell keeps a cell state $c_t$ controlled by forget, input and output gates, which lets it carry information over
# long spans and avoids the vanishing-gradient problem of a plain RNN.

# %% title: Defining the SimpleRNN and LSTM language models
def build(kind, units=256):
    Rnn = {"SimpleRNN": layers.SimpleRNN, "LSTM": layers.LSTM}[kind]
    return keras.Sequential([
        layers.Input((None,)),
        layers.Embedding(V, 64),
        Rnn(units, return_sequences=True),
        layers.Dense(V),
    ], name=kind.lower() + "_lm")
for k in ("SimpleRNN", "LSTM"):
    m = build(k); print(f"{k}: {m.count_params():,} parameters")
build("LSTM").summary(print_fn=print)

# %% title: Training both models (cross-entropy / perplexity per epoch)
loss = keras.losses.SparseCategoricalCrossentropy(from_logits=True)
hist, models = {}, {}
for kind, epochs in (("SimpleRNN", 6), ("LSTM", 12)):
    m = build(kind); m.compile(keras.optimizers.Adam(3e-3, clipnorm=1.0), loss)
    t0 = time.time()
    hist[kind] = m.fit(train_ds, validation_data=val_ds, epochs=epochs, verbose=2).history
    models[kind] = m
    print(f"{kind}: {time.time() - t0:.0f}s | final val loss {hist[kind]['val_loss'][-1]:.3f} | "
          f"val perplexity {np.exp(hist[kind]['val_loss'][-1]):.2f}\n")

# %% title: Training curves and perplexity
fig, ax = plt.subplots(1, 2, figsize=(10, 3.4))
for k, c in (("SimpleRNN", "tab:orange"), ("LSTM", "tab:blue")):
    e = range(1, len(hist[k]["loss"]) + 1)
    ax[0].plot(e, hist[k]["loss"], "o-", c=c, label=k + " train"); ax[0].plot(e, hist[k]["val_loss"], "s--", c=c, label=k + " val")
    ax[1].plot(e, np.exp(hist[k]["val_loss"]), "s-", c=c, label=k)
ax[0].set(title="Cross-entropy loss", xlabel="epoch"); ax[0].legend(fontsize=7)
ax[1].set(title="Validation perplexity (lower is better)", xlabel="epoch"); ax[1].legend()
plt.tight_layout(); plt.show()

# %% [markdown]
# ## 3. Generating text
# Starting from a seed string, we repeatedly predict a distribution over the next character, divide the logits by a
# **temperature** $T$ and sample. Low $T$ gives safe, repetitive text; high $T$ gives creative but error-prone text.

# %% title: Text generation function
def generate(model, seed, n=400, temperature=1.0):
    ids = [c2i[c] for c in seed]
    out = list(seed)
    for _ in range(n):
        logits = model(np.array([ids[-SEQ:]]), training=False)[0, -1].numpy() / temperature
        p = np.exp(logits - logits.max()); p /= p.sum()
        nxt = np.random.choice(V, p=p)
        ids.append(nxt); out.append(i2c[nxt])
    return "".join(out)
np.random.seed(5)
print("generate() defined; sampling with temperature scaling")

# %% title: Text generated by the LSTM at different temperatures
seed = "ROMEO:\n"
for T in (0.3, 0.7, 1.0):
    print(f"======== LSTM, temperature {T} ========")
    print(generate(models["LSTM"], seed, 350, T), "\n")

# %% title: Comparison - SimpleRNN vs LSTM (temperature 0.7)
np.random.seed(5)
for k in ("SimpleRNN", "LSTM"):
    print(f"======== {k} ========")
    print(generate(models[k], "First Citizen:\n", 300, 0.7), "\n")

# %% title: Quality metrics of generated text
vocab_words = set(text.lower().replace("\n", " ").split())
def real_word_rate(s):
    w = [x.strip(".,;:!?'\"") for x in s.lower().replace("\n", " ").split()]
    w = [x for x in w if x]
    return sum(x in vocab_words for x in w) / max(1, len(w))
rows = []
np.random.seed(1)
for k in ("SimpleRNN", "LSTM"):
    for T in (0.3, 0.7, 1.0, 1.3):
        s = generate(models[k], "ROMEO:\n", 600, T)
        rows.append((k, T, real_word_rate(s)))
print(f"{'model':10s} {'temp':>5s}  words found in training vocabulary")
for k, T, r in rows: print(f"{k:10s} {T:5.1f}  {100 * r:5.1f}%")
fig, ax = plt.subplots(figsize=(6, 3))
for k, c in (("SimpleRNN", "tab:orange"), ("LSTM", "tab:blue")):
    ax.plot([r[1] for r in rows if r[0] == k], [100 * r[2] for r in rows if r[0] == k], "o-", c=c, label=k)
ax.set(xlabel="temperature", ylabel="% valid words", title="Valid-word rate vs temperature"); ax.legend()
plt.tight_layout(); plt.show()
