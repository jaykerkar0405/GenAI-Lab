# %% title: Launching the Gradio server in the background
env = dict(os.environ, NO_PROXY="127.0.0.1,localhost", no_proxy="127.0.0.1,localhost")
gproc = subprocess.Popen([sys.executable, "app_gradio.py"], env=env, stdout=open("gradio.log", "w"), stderr=subprocess.STDOUT)
def wait_for(url, timeout=120):
    t0 = time.time()
    while time.time() - t0 < timeout:
        try:
            r = urllib.request.urlopen(url, timeout=2); return r.status, time.time() - t0
        except Exception: time.sleep(1)
    return None, timeout
status, secs = wait_for("http://127.0.0.1:7861/")
print(f"Gradio server on http://127.0.0.1:7861 -> HTTP {status} after {secs:.1f}s")

