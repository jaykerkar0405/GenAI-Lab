# ## 5. Browser screenshots of both running apps
# A headless Chromium (Playwright) opens each application, fills the form and clicks the button, as a user would.

# %% title: Browser automation script
shot_code = r'''
import sys, glob
from playwright.sync_api import sync_playwright
exe = glob.glob("/opt/pw-browsers/chromium-*/chrome-linux*/chrome")[0]
which = sys.argv[1]
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=exe, args=["--no-proxy-server", "--no-sandbox"])
    pg = b.new_page(viewport={"width": 1100, "height": 640})
    if which == "gradio":
        pg.goto("http://127.0.0.1:7861/"); pg.wait_for_selector("text=Handwritten Digit Generator", timeout=60000)
        pg.get_by_role("button", name="Submit").click(); pg.wait_for_selector("img[src*='file=']", timeout=60000)
        pg.wait_for_timeout(1500); pg.screenshot(path="screenshot_gradio.png")
    else:
        pg.goto("http://127.0.0.1:8601/"); pg.wait_for_selector("text=Handwritten Digit Generator", timeout=90000)
        pg.get_by_role("button", name="Generate").click(); pg.wait_for_selector("text=Generated 8 images", timeout=60000)
        pg.wait_for_timeout(1500); pg.screenshot(path="screenshot_streamlit.png", full_page=True)
    b.close()
'''
