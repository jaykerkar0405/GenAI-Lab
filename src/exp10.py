# %% [markdown]
# # Experiment 10: Deployment of a Generative AI Application using Gradio / Streamlit
#
# **Aim:** Train a small conditional generative model (a conditional VAE for handwritten digits), package it, and deploy it as
# an interactive web application with **Gradio** and with **Streamlit**; test the running apps through their API and a browser.

# %% title: Imports and setup
import os, sys, time, subprocess, urllib.request, textwrap
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
os.environ["GRADIO_ANALYTICS_ENABLED"] = "False"
import numpy as np, matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
import gradio, streamlit
keras.utils.set_random_seed(10)
print("TensorFlow", tf.__version__, "| Gradio", gradio.__version__, "| Streamlit", streamlit.__version__)

# %% [markdown]
# ## 1. The model: a conditional VAE
# The decoder receives the latent vector $z$ *and* a one-hot digit label, so the app can generate any requested digit.
# The size of the latent noise controls the variety of handwriting styles.

# %% title: Training the conditional VAE
(x_train, y_train), (x_test, y_test) = keras.datasets.mnist.load_data()
x_train = (x_train / 255.0).astype("float32")[..., None]
y_oh = keras.utils.to_categorical(y_train, 10).astype("float32")
LAT = 8

class Sampling(layers.Layer):
    def call(self, inp):
        mu, lv = inp; return mu + tf.exp(0.5 * lv) * tf.random.normal(tf.shape(mu))

class KLLoss(layers.Layer):
    """adds the KL divergence of q(z|x) from N(0, I) to the training loss"""
    def call(self, inp):
        mu, lv = inp
        self.add_loss(tf.reduce_mean(-0.5 * tf.reduce_sum(1 + lv - tf.square(mu) - tf.exp(lv), axis=1)))
        return inp

img_in, lab_in = keras.Input((28, 28, 1)), keras.Input((10,))
h = layers.Concatenate()([layers.Flatten()(img_in), lab_in])
h = layers.Dense(256, activation="relu")(h)
mu, lv = KLLoss()([layers.Dense(LAT)(h), layers.Dense(LAT)(h)])
z = Sampling()([mu, lv])
z_in, l_in = keras.Input((LAT,)), keras.Input((10,))
d = layers.Dense(256, activation="relu")(layers.Concatenate()([z_in, l_in]))
d = layers.Dense(784, activation="sigmoid")(d)
decoder = keras.Model([z_in, l_in], layers.Reshape((28, 28, 1))(d), name="digit_decoder")
cvae = keras.Model([img_in, lab_in], decoder([z, lab_in]), name="cvae")
recon_loss = lambda x, xh: tf.reduce_sum(keras.losses.binary_crossentropy(x, xh), axis=(1, 2))
cvae.compile(keras.optimizers.Adam(1e-3), loss=recon_loss)
hist = cvae.fit([x_train, y_oh], x_train, epochs=12, batch_size=128, verbose=2)
decoder.save("digit_decoder.keras")
print("saved model:", os.path.abspath("digit_decoder.keras"), "| size: %.1f KB" % (os.path.getsize("digit_decoder.keras") / 1024))

# %% title: Sanity check - generating every digit before deployment
def generate(digit, n=8, variation=1.0, seed=0):
    r = np.random.default_rng(seed)
    z = (variation * r.standard_normal((n, LAT))).astype("float32")
    lab = keras.utils.to_categorical([digit] * n, 10).astype("float32")
    return decoder.predict([z, lab], verbose=0)[..., 0]
fig, axes = plt.subplots(10, 8, figsize=(6, 7.4))
for dgt in range(10):
    for k, im in enumerate(generate(dgt, 8, 1.0, dgt)): axes[dgt, k].imshow(im, cmap="gray"); axes[dgt, k].axis("off")
plt.suptitle("Digits 0-9 generated by the conditional VAE", y=0.995); plt.tight_layout(); plt.show()

# %% [markdown]
# ## 2. The Gradio application
# `gr.Interface` builds a web UI around a Python function: inputs (dropdown, sliders, number) are mapped to the function arguments and
# the returned image is displayed. The same file can be deployed on Hugging Face Spaces.

# %% title: Writing the Gradio app file (app_gradio.py)
MODEL = os.path.abspath("digit_decoder.keras")
gradio_code = f'''import os
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
import numpy as np, gradio as gr
from tensorflow import keras
from PIL import Image

LAT = {LAT}
decoder = keras.models.load_model(r"{MODEL}", compile=False)

def generate(digit, n_samples, variation, seed):
    rng = np.random.default_rng(int(seed))
    n = int(n_samples)
    z = (variation * rng.standard_normal((n, LAT))).astype("float32")
    lab = keras.utils.to_categorical([int(digit)] * n, 10).astype("float32")
    imgs = decoder.predict([z, lab], verbose=0)[..., 0]
    cols = min(n, 4); rows = -(-n // cols)
    canvas = np.zeros((rows * 28, cols * 28))
    for i, im in enumerate(imgs):
        canvas[(i // cols) * 28:(i // cols + 1) * 28, (i % cols) * 28:(i % cols + 1) * 28] = im
    return Image.fromarray((canvas * 255).astype("uint8")).resize((cols * 112, rows * 112), Image.NEAREST)

demo = gr.Interface(
    fn=generate,
    inputs=[gr.Dropdown(list(range(10)), value=7, label="Digit to generate"),
            gr.Slider(1, 16, value=8, step=1, label="Number of samples"),
            gr.Slider(0.1, 2.0, value=1.0, step=0.1, label="Style variation (latent noise scale)"),
            gr.Number(value=42, label="Random seed")],
    outputs=gr.Image(label="Generated handwriting"),
    title="Handwritten Digit Generator",
    description="A conditional VAE trained on MNIST. Pick a digit and generate new handwriting styles.",
    flagging_mode="never",
)
if __name__ == "__main__":
    demo.launch(server_name="127.0.0.1", server_port=7861)
'''
open("app_gradio.py", "w").write(gradio_code)
print(gradio_code)

# %% title: Writing the Streamlit app file (app_streamlit.py)
streamlit_code = f'''import os
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
import numpy as np, streamlit as st
from tensorflow import keras

LAT = {LAT}
st.set_page_config(page_title="Digit Generator", layout="centered")

@st.cache_resource
def load():
    return keras.models.load_model(r"{MODEL}", compile=False)

decoder = load()
st.title("Handwritten Digit Generator (Streamlit)")
st.caption("A conditional VAE trained on MNIST - choose a digit and generate new handwriting styles.")
digit = st.selectbox("Digit to generate", list(range(10)), index=3)
n = st.slider("Number of samples", 1, 16, 8)
variation = st.slider("Style variation", 0.1, 2.0, 1.0, 0.1)
seed = st.number_input("Random seed", value=42, step=1)

if st.button("Generate", type="primary"):
    rng = np.random.default_rng(int(seed))
    z = (variation * rng.standard_normal((n, LAT))).astype("float32")
    lab = keras.utils.to_categorical([digit] * n, 10).astype("float32")
    imgs = decoder.predict([z, lab], verbose=0)[..., 0]
    st.image(list(imgs), width=100, clamp=True)
    st.success(f"Generated {{n}} images of the digit {{digit}}")
'''
open("app_streamlit.py", "w").write(streamlit_code)
print("app_streamlit.py written:", len(streamlit_code.splitlines()), "lines")

